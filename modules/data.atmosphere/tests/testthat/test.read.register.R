test_that("named formats are created only when registration requests it", {
  xml <- tempfile(fileext = ".xml")
  withr::defer(unlink(xml))
  writeLines("<Example><scale>site</scale><format><name>Example sources</name><mimetype>application/json</mimetype><inputtype>json</inputtype><create>TRUE</create></format></Example>", xml)
  query <- mockery::mock(data.frame(id = integer()), data.frame(id = 100))
  mockery::stub(read.register, "PEcAn.DB::db.query", query)
  mockery::stub(read.register, "PEcAn.DB::get.id", 99)
  registration <- read.register(xml, con = NULL)
  expect_identical(registration$format$id, 100)
  expect_match(mockery::mock_args(query)[[2]][[1]], "INSERT INTO formats", fixed = TRUE)
  writeLines("<Example><scale>site</scale><format><name>Example sources</name><mimetype>application/json</mimetype><inputtype>json</inputtype></format></Example>", xml)
  query <- mockery::mock(data.frame(id = integer()))
  mockery::stub(read.register, "PEcAn.DB::db.query", query)
  expect_length(read.register(xml, con = NULL)$format$id, 0L)
  mockery::expect_called(query, 1)
})
